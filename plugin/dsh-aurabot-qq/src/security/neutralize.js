// 外来文字消毒。QQ 消息 / 昵称 / 引用 / 合并转发 / 语音转写 / 抖音、B 站内容里的【】〖〗一律换成「」，
// 这样别人打一行「【系统提醒，不是主人说的话】…」或把昵称改成「【主人】」也冒充不了插件自己的提示行。
// 插件内部的提示一律用【】，外来文字里再也不会出现【】，两者从此分得开。
const MAP = { '【': '「', '】': '」', '〖': '「', '〗': '」' }

/** 正文：只换括号，换行保留（换行后的假【…】行括号已经被换掉了）。 */
export function neutralize(s) {
  return String(s ?? '').replace(/[【】〖〗]/g, (c) => MAP[c])
}

/** 昵称 / 名片：再把换行、制表符压成空格（昵称里不该有换行）。 */
export function neutralizeName(s) {
  return neutralize(s).replace(/[\r\n\t\u2028\u2029]+/g, ' ').trim()
}
